function normalizeAccessToken(raw) {
  let t = (raw || "").trim();
  if (t.startsWith('"') && t.endsWith('"') || t.startsWith("'") && t.endsWith("'")) {
    t = t.slice(1, -1).trim();
  }
  while (/^bearer\s+/i.test(t)) {
    t = t.replace(/^bearer\s+/i, "").trim();
  }
  try {
    if (t.includes("%")) {
      const decoded = decodeURIComponent(t);
      if (decoded && decoded !== t) t = decoded;
    }
  } catch (e) {
  }
  return t.trim();
}
