function findBoardsByQuery(q, limit = 30) {
  const s = (q || "").trim().toLowerCase();
  if (!s) return BOARD_LIST.slice().sort((a, b) => a.name.localeCompare(b.name, "zh-CN"));
  if (/^\d+$/.test(s)) {
    const id = parseInt(s, 10);
    return BOARD_LIST.filter((b) => b.id === id);
  }
  const scored = BOARD_LIST.map((b) => {
    const n = b.name.toLowerCase();
    let score = 0;
    if (n === s) score = 100;
    else if (n.startsWith(s)) score = 80;
    else if (n.includes(s)) score = 50;
    return { b, score };
  }).filter((x) => x.score > 0);
  scored.sort((a, b) => b.score - a.score || a.b.name.localeCompare(b.b.name, "zh-CN"));
  return scored.slice(0, limit).map((x) => x.b);
}
